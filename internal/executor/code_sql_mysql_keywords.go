func sqlNavKeywordSet(source string) map[string]bool {
	result := make(map[string]bool)
	for _, word := range strings.Fields(source) {
		result[word] = true
	}
	return result
}

// A reserved word is allowed unquoted only *after* a period in a qualified
// name. Quoted names bypass keyword classification, but not sqlNavName's
// separate lexical/escaping/length validation.
func sqlNavMySQLBareIdentifierAllowed(token sqlDDLToken, dialect string, afterDot bool) bool {
	if token.kind == 'q' {
		return true
	}
	if token.kind != 'i' || !sqlNavSimpleName.MatchString(token.text) {
		return false
	}
	if afterDot {
		return true
	}
	switch dialect {
	case "mysql":
		return !sqlNavMySQL84Reserved[token.keyword()]
	case "mariadb":
		return !sqlNavMariaDBReserved[token.keyword()]
	default:
		return false
	}
}

// Called only after sqlNavName has validated complete, bounded qualification.
func sqlNavMySQLNameAllowed(tokens []sqlDDLToken, start, end int, dialect string) bool {
	if end <= start || end-start > 3 {
		return false
	} // table: [database.]relation
	for at := start; at < end; at += 2 {
		if !sqlNavMySQLBareIdentifierAllowed(tokens[at], dialect, at > start) {
			return false
		}
	}
	return true
}
