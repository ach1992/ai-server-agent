package systemexec

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
)

// The same deterministic tree digest is used for npm-installed language
// servers, extracted Python wheels and native resource bundles. It includes
// every file name, file byte length, content and directory name; modes/owner
// and symlinks have separate trust checks.
type nodeModulePolicy struct {
	label     string
	fileCount int
	dirCount  int
	maxBytes  int64
	digest    string
}

type ResourceTreeInspection struct {
	SHA256 string `json:"sha256"`
	Files  int    `json:"file_count"`
	Dirs   int    `json:"dir_count"`
	Bytes  int64  `json:"bytes"`
}

func verifyPinnedNodeModules(root string, requireRoot bool, p nodeModulePolicy) error {
	if p.label == "" || p.fileCount <= 0 || p.dirCount < 0 || p.maxBytes <= 0 ||
		len(p.digest) != sha256.Size*2 || filepath.Clean(root) != root || !filepath.IsAbs(root) {
		return errors.New("invalid_node_module_policy")
	}
	result, err := inspectResourceTree(root, requireRoot, p.maxBytes, p.fileCount, p.dirCount, p.label)
	if err != nil {
		return err
	}
	if result.Files != p.fileCount || result.Dirs != p.dirCount || result.SHA256 != p.digest {
		return fmt.Errorf("%s_dependency_tree_digest_mismatch", p.label)
	}
	return nil
}

// InspectResourceTree is an operator/developer preparation aid. It does not
// trust or activate the inspected directory. Runtime callers always verify
// against an administrator-owned profile and exact expected digest.
func InspectResourceTree(root string, maxBytes int64) (ResourceTreeInspection, error) {
	return inspectResourceTree(root, false, maxBytes, 0, 0, "adapter_tree")
}

func inspectResourceTree(root string, requireRoot bool, maxBytes int64, maxFiles, maxDirs int, label string) (ResourceTreeInspection, error) {
	var report ResourceTreeInspection
	failure := func(reason string) error { return fmt.Errorf("%s_%s", label, reason) }
	if maxBytes <= 0 || !filepath.IsAbs(root) || filepath.Clean(root) != root || label == "" {
		return report, errors.New("invalid_node_module_policy")
	}
	if _, err := os.Lstat(filepath.Join(root, ".bin")); !os.IsNotExist(err) {
		return report, failure("unwanted_package_bin_wrappers")
	}
	info, err := os.Lstat(root)
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return report, failure("root_directory_invalid")
	}
	if requireRoot {
		st, ok := info.Sys().(*syscall.Stat_t)
		if !ok || st.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return report, failure("untrusted_dependency_ownership")
		}
	}
	h := sha256.New()
	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return failure("dependency_tree_inaccessible")
		}
		if path == root {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil || rel == "." || len(rel) > 512 || strings.ContainsRune(rel, 0) {
			return failure("invalid_dependency_path")
		}
		rel = filepath.ToSlash(rel)
		fi, err := os.Lstat(path)
		if err != nil || fi.Mode()&os.ModeSymlink != 0 {
			return failure("unsafe_dependency_type")
		}
		if requireRoot {
			st, ok := fi.Sys().(*syscall.Stat_t)
			if !ok || st.Uid != 0 || fi.Mode().Perm()&0022 != 0 {
				return failure("untrusted_dependency_ownership")
			}
		}
		if fi.IsDir() {
			report.Dirs++
			if (maxDirs > 0 && report.Dirs > maxDirs) || (requireRoot && fi.Mode().Perm()&0005 != 0005) {
				return failure("dependency_directory_invalid")
			}
			_, _ = io.WriteString(h, "d\x00"+rel+"\x00")
			return nil
		}
		if !fi.Mode().IsRegular() || fi.Size() < 0 ||
			(maxFiles > 0 && report.Files >= maxFiles) || report.Bytes > maxBytes-fi.Size() ||
			(requireRoot && fi.Mode().Perm()&0004 != 0004) {
			return failure("dependency_file_invalid")
		}
		report.Files++
		report.Bytes += fi.Size()
		_, _ = io.WriteString(h, "f\x00"+rel+"\x00"+strconv.FormatInt(fi.Size(), 10)+"\x00")
		f, err := os.Open(path)
		if err != nil {
			return failure("dependency_unreadable")
		}
		count, readErr := io.Copy(h, io.LimitReader(f, fi.Size()+1))
		closeErr := f.Close()
		if readErr != nil || closeErr != nil || count != fi.Size() {
			return failure("dependency_changed_during_read")
		}
		return nil
	})
	if err != nil {
		return ResourceTreeInspection{}, err
	}
	report.SHA256 = hex.EncodeToString(h.Sum(nil))
	return report, nil
}
